while True:
    opcion = int(input("Escoge una opción [1] Registrarse [2] Iniciar sesión [3] Salir -> "))
    match opcion:
        case 1:
            print("Opción 1: Registrarse")
            break
        case 2:
            print("Opción 2: Iniciar sesión")
            break
        case 3:
            print("Saliste del menú")
            break
        case _:
            print("Opción no disponible, elige nuevamente.")